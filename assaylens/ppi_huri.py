"""Curated HuRI research data adapter for the AssayLens protein interaction workspace."""
from __future__ import annotations

import importlib
import hashlib
from datetime import datetime, timezone
import pandas as pd

AA=set('ACDEFGHIKLMNPQRSTVWY')


def _choose(df, names):
    columns={str(x).lower():x for x in df.columns}
    for candidate in names:
        if candidate.lower() in columns:
            return df[columns[candidate.lower()]]
    return pd.Series(['']*len(df),index=df.index)


def load_huri(include_reference_controls=False):
    try:
        mod=importlib.import_module('tdc.multi_pred')
    except ImportError:
        try:
            mod=importlib.import_module('tdc_ml.multi_pred')
        except ImportError as exc:
            raise RuntimeError('Install optional PyTDC: py -3 -m pip install PyTDC') from exc
    data=mod.PPI(name='HuRI')
    if include_reference_controls:
        data=data.neg_sample(frac=1)
    return data.get_data() if hasattr(data,'get_data') else data


def normalize_huri(raw:pd.DataFrame, max_rows=10000, seed=42, include_reference_controls=False):
    if not isinstance(raw,pd.DataFrame) or raw.empty:
        raise ValueError('HuRI returned no data')
    if not 100<=max_rows<=20000:
        raise ValueError('Choose a row cap between 100 and 20,000')
    df=pd.DataFrame({
        'protein_a': _choose(raw,['Protein1','protein_a','Sequence1']),
        'protein_b': _choose(raw,['Protein2','protein_b','Sequence2']),
        'protein_a_id': _choose(raw,['Protein1_ID','protein_a_id']),
        'protein_b_id': _choose(raw,['Protein2_ID','protein_b_id']),
        'label': pd.to_numeric(_choose(raw,['Y','label']),errors='coerce'),
    })
    if not include_reference_controls:
        # HuRI is released as a positive interaction network; when its raw
        # table omits Y, interpret reported links as positives, not negatives.
        df['label']=df['label'].fillna(1)
    df['protein_a']=df['protein_a'].astype(str).str.strip().str.upper()
    df['protein_b']=df['protein_b'].astype(str).str.strip().str.upper()
    lengths_a=df['protein_a'].str.len()
    lengths_b=df['protein_b'].str.len()
    valid=(lengths_a.between(30,10000) & lengths_b.between(30,10000)
           & df.protein_a.map(lambda x: set(x)<=AA)
           & df.protein_b.map(lambda x: set(x)<=AA)
           & df.label.isin([0,1]))
    excluded=int((~valid).sum())
    df=df.loc[valid].copy()
    if df.empty:
        raise ValueError('No unambiguous sequence pairs remain after filtering')
    if len(df)>max_rows:
        df=df.sample(n=max_rows,random_state=seed).reset_index(drop=True)
    df['interaction_type']='HuRI_binary_protein_association'
    df['source_id']='TDC_HuRI'
    df['evidence_type']='TDC_reference_control_sampling' if include_reference_controls else 'reported_positive_network_edge'
    audit={
        'source':'Therapeutics Data Commons / HuRI',
        'source_documentation':'https://tdcommons.ai/multi_pred_tasks/ppi/',
        'retrieved_utc':datetime.now(timezone.utc).isoformat(),
        'input_rows':int(len(raw)),'ambiguous_or_invalid_rows':excluded,
        'export_rows':int(len(df)),'max_rows':int(max_rows),'seed':int(seed),
        'reference_controls_included':bool(include_reference_controls),
        'trainable_binary_labels':bool(df.label.eq(0).any() and df.label.eq(1).any()),
        'limitations':[
            'Reference controls generated by TDC are not manually confirmed negative experiments.',
            'Exclude ambiguous protein sequence isoforms containing * separators.',
            'Exact protein identity separation does not guarantee homology-disjoint evaluation.',
            'Network evidence and experimental negative evidence require independent scrutiny.',
        ]
    }
    audit['table_sha256']=hashlib.sha256(df.to_csv(index=False).encode()).hexdigest()
    return df,audit
